/* Real browser -> HTTP server -> subprocess ADB fixture. No physical-device claims. */
const {chromium} = require(process.env.FIRETV_PLAYWRIGHT || 'playwright');
const {spawn} = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'firetv-browser-'));
const server = spawn('python3', ['-u', path.join(__dirname, 'panel_fixture.py')], {cwd: root, env: {...process.env, FIRETV_CONFIG: path.join(tmp, 'device.json'), FIRETV_TEST_LOG: path.join(tmp, 'commands.jsonl')}});
let browser;
(async () => {
  const url = await new Promise((resolve, reject) => {
    let output = '';
    const timeout = setTimeout(() => reject(new Error('Panel did not start')), 10000);
    server.stdout.on('data', chunk => { output += chunk; const match = output.match(/http:\/\/127\.0\.0\.1:\d+\/#[\w-]+/); if (match) { clearTimeout(timeout); resolve(match[0]); } });
    server.on('error', reject);
    server.on('exit', code => { if (code) reject(new Error(`Panel exited: ${code}`)); });
  });
  browser = await chromium.launch({headless: true});
  const page = await browser.newPage({viewport: {width: 1440, height: 1050}});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()); });
  page.on('dialog', dialog => dialog.accept());
  await page.goto(url);
  await page.waitForFunction(() => !document.querySelector('#refresh').disabled);
  assert.equal(await page.locator('#capture').isDisabled(), true);
  await page.locator('#address').fill('192.168.1.50');
  await page.locator('#connect-form button').click();
  await page.waitForFunction(() => document.querySelector('#connection-status').textContent.includes('Conectado'));
  await page.waitForFunction(() => !document.querySelector('#capture').disabled);
  assert.equal(await page.locator('#device-model').innerText(), 'Fire TV TEST');
  await page.locator('[data-key=right]').click();
  await page.waitForFunction(() => !document.querySelector('#capture').disabled);
  await page.locator('#remote-text').fill('hello fire tv');
  await page.locator('#text-form button').click();
  await page.waitForFunction(() => !document.querySelector('#capture').disabled);
  await page.locator('#capture').click();
  await page.locator('#screenshot').waitFor({state: 'visible'});
  await page.waitForFunction(() => !document.querySelector('#capture').disabled);
  await page.locator('[data-tab=apps]').click();
  await page.locator('#app-list .list-row').first().waitFor();
  await page.waitForFunction(() => !document.querySelector('#load-apps').disabled);
  assert.equal(await page.locator('#app-list .list-row').count(), 2);
  await page.locator('#app-search').fill('player');
  assert.equal(await page.locator('#app-list .list-row').count(), 1);
  await page.locator('#app-search').fill('');
  await page.locator('#apk-file').setInputFiles({name:'example.apk', mimeType:'application/vnd.android.package-archive', buffer:Buffer.from('test apk')});
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('APK instalado com sucesso'));
  await page.locator('#app-list button').filter({hasText:'Desinstalar'}).first().click();
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Aplicativo desinstalado'));
  await page.locator('#all-apps').check();
  await page.waitForFunction(() => !document.querySelector('#load-apps').disabled);
  assert.equal(await page.locator('#app-list button').filter({hasText:'Desinstalar'}).count(), 0);
  await page.locator('[data-tab=files]').click();
  await page.locator('#file-list .list-row').first().waitFor();
  await page.waitForFunction(() => !document.querySelector('#parent-folder').disabled);
  assert.equal(await page.locator('#file-list .list-row').count(), 4);
  assert.ok((await page.locator('#file-list').innerText()).includes("a'$(touch owned).txt"));
  const download = page.waitForEvent('download');
  await page.locator('#file-list button').filter({hasText:'Baixar'}).first().click();
  assert.ok((await download).suggestedFilename().endsWith('.txt'));
  await page.waitForFunction(() => !document.querySelector('#parent-folder').disabled);
  await page.locator('#transfer-file').setInputFiles({name:'sample.txt', mimeType:'text/plain', buffer:Buffer.from('hello')});
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Arquivo enviado para a TV'));
  await page.locator('[data-tab=home]').click();
  await page.locator('#home-list .list-row').waitFor();
  await page.waitForFunction(() => !document.querySelector('#load-home').disabled);
  assert.ok((await page.locator('#current-home').innerText()).includes('com.amazon.tv.launcher'));
  await page.locator('#home-list button').click();
  await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Launcher aberto'));
  // Regression: changing devices must not expose the previous device's files or image.
  await page.locator('#disconnect').click();
  await page.waitForFunction(() => document.querySelector('#connection-status').textContent === 'Desconectado');
  assert.equal(await page.locator('#screenshot').isVisible(), false);
  const artifacts = path.join(root, 'artifacts'); fs.mkdirSync(artifacts, {recursive:true});
  await page.locator('[data-tab=remote]').click();
  await page.screenshot({path:path.join(artifacts, 'panel-desktop.png'), fullPage:true});
  await page.setViewportSize({width:390, height:844});
  await page.screenshot({path:path.join(artifacts, 'panel-mobile.png'), fullPage:true});
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  assert.equal(overflow, false, 'Mobile page must not overflow horizontally');
  const commands = fs.readFileSync(path.join(tmp, 'commands.jsonl'), 'utf8').trim().split('\n').map(JSON.parse);
  assert.ok(commands.some(c => c.includes('install')));
  assert.ok(commands.some(c => c.includes('uninstall')));
  assert.ok(commands.some(c => c.includes('push')));
  assert.ok(commands.some(c => c.includes('pull')));
  assert.ok(commands.some(c => c.includes('shell') && c.some(s => s.includes('input keyevent 22'))));
  assert.deepEqual(errors, []);
  console.log('Browser checks passed: connection, remote, text, screenshot, apps, install/uninstall, upload/download, launchers, disconnect, mobile layout.');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { if(browser) await browser.close(); server.kill(); fs.rmSync(tmp, {recursive:true, force:true}); });
